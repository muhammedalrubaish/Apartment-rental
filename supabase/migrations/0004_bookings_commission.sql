-- عمولة المنصة داخل الحجز (public.bookings)
-- يُطبَّق مرة واحدة على مشروع Supabase (SQL Editor أو supabase db push)
--
-- الخلفية: كانت العمولة تُسجَّل صفاً في جدول المصاريف بحالة «مستحق»،
-- فتظهر في «الفواتير والمستحقات» كأنها فاتورة على المالك أن يسددها.
-- الحقيقة أن المنصة تحجز عمولتها من المبلغ الإجمالي قبل التحويل،
-- فهي ليست فاتورة بل خصم داخل الحجز نفسه.
--
-- بعد هذه الهجرة:
--   إيراد الحجز الصافي = total - commission
--   وجدول المصاريف يبقى للمصاريف التشغيلية الحقيقية (نظافة، كهرباء، إنترنت)

alter table public.bookings
  add column if not exists commission numeric not null default 0;

comment on column public.bookings.commission is
  'عمولة المنصة المحجوزة من المبلغ الإجمالي بالريال — صفر للحجوزات المباشرة';

-- ملاحظة: ترحيل صفوف العمولة القديمة من جدول المصاريف إلى هذا العمود
-- يتم من لوحة التحكم بزر «ترحيل العمولات من الفواتير» (الإعدادات ← عمولة المنصات)،
-- لأن الربط يعتمد على مطابقة اسم الضيف والمنصة وتاريخ الوصول في ملاحظة المصروف.
